import { createContext, useContext } from 'react';

/**
 * Канал «закрой меня» между слоем прогулки и плашкой внутри него.
 *
 * Почему контекст, а не Render Props. Стейт закрытия живёт в FrameObserver —
 * он единственный знает, виден ли слой сейчас, и он же решает, когда стейт
 * сбросить. Плашке нужна оттуда ровно одна функция. Прокидывать её через
 * children-as-function означало бы превратить каждый вызов в App.tsx в тело
 * функции и ломать мемоизацию баннеров новой идентичностью замыкания на каждом
 * рендере обёртки. Контекст оставляет разметку страницы декларативной, а
 * сигнатуру children — прежней.
 *
 * Провайдера-компонента здесь нет намеренно: значение создаёт сам
 * FrameObserver, а держать хук и компонент в одном файле мешает Fast Refresh.
 */

export interface BannerDismissApi {
    /**
     * Закрывает слой: запускает анимацию ухода и мгновенно снимает клики.
     * Идентичность стабильна на всё время жизни слоя.
     */
    close: () => void;
}

export const BannerDismissContext = createContext<BannerDismissApi | null>(null);

/**
 * null — законное и ожидаемое значение, а не ошибка.
 *
 * Те же баннеры рендерятся в StaticGallery, где никакой прогулки нет и
 * закрывать нечего. Поэтому хук не бросает исключение (в отличие от
 * useFrameProgress): null означает «этот баннер сейчас не в закрываемом слое»,
 * и плашка просто не рисует крестик.
 */
export function useBannerDismiss(): BannerDismissApi | null {
    return useContext(BannerDismissContext);
}
